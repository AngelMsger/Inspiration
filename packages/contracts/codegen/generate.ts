// Generate the contracts from schema/*.yaml.
//
// Writes:
//   dist/inspiration.schema.json  every type in one flat $defs namespace (the input of all
//                                 validators, and the file consumers in other languages read)
//   src/generated.ts              one exported type per schema type
//   src/events.ts                 the event catalogue from the x-events of events.yaml
//
// Type names must be unique across files. Cross-file references
// ("knowledge.yaml#/$defs/Claim") become local ones ("#/$defs/Claim").
//
// Usage: node packages/contracts/codegen/generate.ts [--check]

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { Ajv2020 } from "ajv/dist/2020.js";
import { compile } from "json-schema-to-typescript";
import { parse } from "yaml";

type Json = null | boolean | number | string | Json[] | { [key: string]: Json };
type JsonObject = { [key: string]: Json };

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const SCHEMA_DIR = join(ROOT, "schema");
const BUNDLE_ID = "https://schemas.inspiration.local/contracts/v1/inspiration.schema.json";
const HEADER = "// Generated by packages/contracts/codegen/generate.ts from packages/contracts/schema. Do not edit.\n";
const REF = /^(?<file>[a-z_]+\.yaml)?#\/\$defs\/(?<name>[A-Za-z0-9]+)$/;

// Unions whose members share a constant tag field. The bundle carries an OpenAPI-style
// "discriminator" keyword (ignored by JSON Schema validators) for code generators.
const DISCRIMINATORS: Record<string, string> = {
  Block: "type",
  DataRef: "kind",
  ViewHostMessage: "type",
  ViewGuestMessage: "type",
};

class BundleError extends Error {}

function isObject(node: Json | undefined): node is JsonObject {
  return typeof node === "object" && node !== null && !Array.isArray(node);
}

function loadSources(): Map<string, JsonObject> {
  const sources = new Map<string, JsonObject>();
  for (const file of readdirSync(SCHEMA_DIR)
    .filter((f) => f.endsWith(".yaml"))
    .sort()) {
    const doc = parse(readFileSync(join(SCHEMA_DIR, file), "utf8")) as JsonObject;
    if (doc.$id !== file) throw new BundleError(`${file}: $id must be "${file}"`);
    sources.set(file, doc);
  }
  return sources;
}

function rewriteRefs(node: Json, file: string, defined: Map<string, string>): Json {
  if (Array.isArray(node)) return node.map((v) => rewriteRefs(v, file, defined));
  if (!isObject(node)) return node;
  const out: JsonObject = {};
  for (const [key, value] of Object.entries(node)) {
    if (key !== "$ref") {
      out[key] = rewriteRefs(value, file, defined);
      continue;
    }
    const m = typeof value === "string" ? REF.exec(value) : null;
    if (!m?.groups) throw new BundleError(`${file}: unsupported $ref ${JSON.stringify(value)}`);
    const name = m.groups.name as string;
    if (defined.get(name) !== (m.groups.file ?? file)) {
      throw new BundleError(`${file}: $ref ${JSON.stringify(value)} does not resolve`);
    }
    out[key] = `#/$defs/${name}`;
  }
  return out;
}

export function bundle(): JsonObject {
  const sources = loadSources();
  const defined = new Map<string, string>();
  for (const [file, doc] of sources) {
    for (const name of Object.keys((doc.$defs as JsonObject | undefined) ?? {})) {
      const other = defined.get(name);
      if (other) throw new BundleError(`type ${name} is defined in both ${other} and ${file}`);
      defined.set(name, file);
    }
  }

  const defs: JsonObject = {};
  const events: JsonObject = {};
  const files: JsonObject = {};
  for (const [file, doc] of sources) {
    const own = (doc.$defs as JsonObject | undefined) ?? {};
    files[file.replace(/\.yaml$/, "")] = Object.keys(own);
    for (const [name, schema] of Object.entries(own)) defs[name] = rewriteRefs(schema, file, defined);
    for (const [type, spec] of Object.entries((doc["x-events"] as JsonObject | undefined) ?? {})) {
      const payload = isObject(spec) ? spec.payload : undefined;
      if (typeof payload !== "string" || !defined.has(payload)) {
        throw new BundleError(`event ${type}: unknown payload ${JSON.stringify(payload)}`);
      }
      events[type] = spec;
    }
  }

  for (const [name, tag] of Object.entries(DISCRIMINATORS)) {
    const union = defs[name] as JsonObject;
    const mapping: JsonObject = {};
    for (const member of union.oneOf as JsonObject[]) {
      const ref = member.$ref as string;
      const target = defs[ref.split("/").pop() as string] as JsonObject;
      const property = (target.properties as JsonObject)[tag] as JsonObject;
      mapping[property.const as string] = ref;
    }
    union.discriminator = { propertyName: tag, mapping };
  }

  const result: JsonObject = {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    $id: BUNDLE_ID,
    title: "Inspiration contracts",
    description: "Generated by packages/contracts/codegen/generate.ts. Do not edit.",
    "x-events": events,
    "x-files": files,
    $defs: Object.fromEntries(
      Object.keys(defs)
        .sort()
        .map((n) => [n, defs[n] as Json]),
    ),
  };
  const ajv = new Ajv2020({ strict: false });
  if (!ajv.validateSchema(result)) throw new BundleError(`invalid schema: ${ajv.errorsText(ajv.errors)}`);
  return result;
}

const SCHEMA_MAPS = ["properties", "patternProperties", "$defs"];
const SCHEMA_LISTS = ["oneOf", "anyOf", "allOf", "prefixItems"];
const SCHEMA_VALUES = ["additionalProperties", "items", "not", "contains", "if", "then", "else"];
const TYPED = ["type", "$ref", "enum", "const", "properties", "items", ...SCHEMA_LISTS];

// Rewrites one schema for json-schema-to-typescript:
// - keywords next to a $ref (usually a field description) make it emit numbered copies of the
//   referenced type (Instant1, Instant2...), so they are dropped;
// - an object with no declared shape is free-form, so it gets an index signature, not `{}`;
// - a schema with no type at all (only a description) accepts any value, which the generator
//   would otherwise type as an object.
function prepare(node: Json): Json {
  if (!isObject(node)) return node;
  if ("$ref" in node) return { $ref: node.$ref as string };
  const out: JsonObject = { ...node };
  for (const key of SCHEMA_MAPS) {
    const map = out[key];
    if (isObject(map)) out[key] = Object.fromEntries(Object.entries(map).map(([k, v]) => [k, prepare(v)]));
  }
  for (const key of SCHEMA_LISTS) if (Array.isArray(out[key])) out[key] = (out[key] as Json[]).map(prepare);
  for (const key of SCHEMA_VALUES) if (key in out) out[key] = prepare(out[key] as Json);
  const shaped = ["properties", "additionalProperties", "patternProperties", "oneOf", "anyOf", "allOf"];
  if (out.type === "object" && !shaped.some((k) => k in out)) out.additionalProperties = true;
  if (!TYPED.some((k) => k in out)) out.tsType = "unknown";
  return out;
}

async function generateTypes(schema: JsonObject): Promise<string> {
  const copy = structuredClone(schema);
  const defs = Object.fromEntries(Object.entries(copy.$defs as JsonObject).map(([n, d]) => [n, prepare(d)]));
  // json-schema-to-typescript names types after `title`, so every definition gets one, and
  // a synthetic root that references all of them makes it emit every type.
  for (const [name, def] of Object.entries(defs)) (def as JsonObject).title = name;
  const root: JsonObject = {
    $defs: defs,
    type: "object",
    additionalProperties: false,
    properties: Object.fromEntries(Object.keys(defs).map((n) => [n, { $ref: `#/$defs/${n}` }])),
  };
  // biome-ignore lint/suspicious/noExplicitAny: the generator's own JSONSchema4 type is looser than ours
  let ts = await compile(root as any, "InspirationContractsRoot", {
    bannerComment: "",
    additionalProperties: false,
    unreachableDefinitions: false,
    declareExternallyReferenced: true,
    enableConstEnums: false,
    strictIndexSignatures: true,
    format: true,
    style: { semi: true, singleQuote: false, printWidth: 100 },
  });
  ts = ts.replace(/export interface InspirationContractsRoot \{[\s\S]*?\n\}\n/, "");
  return `${HEADER}\n${ts.trimStart()}`;
}

function generateEvents(schema: JsonObject): string {
  const events = schema["x-events"] as Record<string, { payload: string; version: number }>;
  const entries = Object.entries(events);
  const payloads = [...new Set(entries.map(([, e]) => e.payload))].sort();
  return [
    HEADER,
    `import type { ${payloads.join(", ")} } from "./generated.ts";`,
    "",
    "/** Every event type in the catalogue, in catalogue order. */",
    "export const EVENT_TYPES = [",
    ...entries.map(([t]) => `  "${t}",`),
    "] as const;",
    "",
    "export type EventTypeName = (typeof EVENT_TYPES)[number];",
    "",
    "/** Payload type for each event type. */",
    "export interface EventPayloads {",
    ...entries.map(([t, e]) => `  "${t}": ${e.payload};`),
    "}",
    "",
    "/** Name of the schema type of each event's payload, for validation. */",
    "export const EVENT_PAYLOAD_TYPES: Readonly<Record<EventTypeName, string>> = {",
    ...entries.map(([t, e]) => `  "${t}": "${e.payload}",`),
    "};",
    "",
    "/** Payload schema version of each event type. Consumers dead-letter newer versions. */",
    "export const EVENT_VERSIONS: Readonly<Record<EventTypeName, number>> = {",
    ...entries.map(([t, e]) => `  "${t}": ${e.version},`),
    "};",
    "",
  ].join("\n");
}

async function main(): Promise<number> {
  const check = process.argv.includes("--check");
  let schema: JsonObject;
  try {
    schema = bundle();
  } catch (e) {
    if (!(e instanceof BundleError)) throw e;
    console.error(`contracts: ${e.message}`);
    return 1;
  }
  const outputs = new Map<string, string>([
    [join(ROOT, "dist", "inspiration.schema.json"), `${JSON.stringify(schema, null, 2)}\n`],
    [join(ROOT, "src", "generated.ts"), await generateTypes(schema)],
    [join(ROOT, "src", "events.ts"), generateEvents(schema)],
  ]);
  const stale = [...outputs].filter(([path, text]) => !existsSync(path) || readFileSync(path, "utf8") !== text);
  if (check) {
    for (const [path] of stale) console.error(`contracts: ${path} is stale; run \`pnpm contracts\``);
    return stale.length ? 1 : 0;
  }
  for (const [path, text] of outputs) writeFileSync(path, text);
  console.log(`contracts: ${Object.keys(schema.$defs as JsonObject).length} types, ${outputs.size} files written`);
  return 0;
}

process.exitCode = await main();
