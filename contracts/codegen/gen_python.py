"""Generate the Python contracts from the bundled schema.

Writes, under contracts/python/src/inspiration/contracts/:
  models.py  pydantic v2 models for every type (datamodel-code-generator)
  events.py  the event registry built from the x-events catalogue

Usage: python contracts/codegen/gen_python.py [--check]
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BUNDLE = ROOT / "dist" / "inspiration.schema.json"
PKG = ROOT / "python" / "src" / "inspiration" / "contracts"

HEADER = "# Generated by contracts/codegen/gen_python.py from contracts/schema. Do not edit.\n"

DATAMODEL_ARGS = [
    "--input-file-type", "jsonschema",
    "--output-model-type", "pydantic_v2.BaseModel",
    "--target-python-version", "3.12",
    "--use-standard-collections",
    "--use-union-operator",
    "--use-type-alias",
    "--use-annotated",
    "--field-constraints",
    "--use-schema-description",
    "--use-field-description",
    "--use-subclass-enum",
    "--enum-field-as-literal", "one",
    "--skip-root-model",
    "--use-one-literal-as-default",
    "--disable-timestamp",
    "--use-double-quotes",
    "--formatters", "ruff-format",
    "--custom-file-header", HEADER.rstrip("\n"),
]  # fmt: skip


def generate_models() -> str:
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "models.py"
        subprocess.run(
            [
                sys.executable,
                "-m",
                "datamodel_code_generator",
                "--input",
                str(BUNDLE),
                "--output",
                str(out),
                *DATAMODEL_ARGS,
            ],
            check=True,
        )
        return out.read_text(encoding="utf-8")


def const_name(event_type: str) -> str:
    return event_type.replace(".", "_").upper()


def generate_events(bundle: dict) -> str:
    events = bundle["x-events"]
    payloads = sorted({spec["payload"] for spec in events.values()})
    lines = [
        HEADER,
        '"""The event catalogue: event type names, payload models and payload versions."""',
        "",
        "from __future__ import annotations",
        "",
        "from enum import StrEnum",
        "from typing import Final",
        "",
        "from pydantic import BaseModel",
        "",
        "from .models import (",
        *[f"    {name}," for name in payloads],
        ")",
        "",
        "",
        "class EventType(StrEnum):",
        *[f'    {const_name(t)} = "{t}"' for t in events],
        "",
        "",
        "PAYLOADS: Final[dict[EventType, type[BaseModel]]] = {",
        *[f"    EventType.{const_name(t)}: {spec['payload']}," for t, spec in events.items()],
        "}",
        "",
        "VERSIONS: Final[dict[EventType, int]] = {",
        *[f"    EventType.{const_name(t)}: {spec['version']}," for t, spec in events.items()],
        "}",
        "",
        "TYPE_OF_PAYLOAD: Final[dict[type[BaseModel], EventType]] = {model: t for t, model in PAYLOADS.items()}",
        "",
    ]
    return "\n".join(lines)


def ruff_format(source: str) -> str:
    result = subprocess.run(
        [sys.executable, "-m", "ruff", "format", "--stdin-filename", "generated.py", "-"],
        input=source,
        capture_output=True,
        text=True,
        check=True,
    )
    return result.stdout


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()

    bundle = json.loads(BUNDLE.read_text(encoding="utf-8"))
    outputs = {
        PKG / "models.py": ruff_format(generate_models()),
        PKG / "events.py": ruff_format(generate_events(bundle)),
    }
    stale = [p for p, text in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if args.check:
        for p in stale:
            print(f"gen_python: {p.relative_to(ROOT.parent)} is stale; run `make contracts`", file=sys.stderr)
        return 1 if stale else 0
    for p, text in outputs.items():
        p.write_text(text, encoding="utf-8")
    print(f"gen_python: wrote {', '.join(str(p.relative_to(ROOT.parent)) for p in outputs)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
