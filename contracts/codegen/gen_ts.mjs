// Generate the TypeScript contracts from the bundled schema.
//
// Writes, under contracts/typescript/src/:
//   generated.ts  one exported type per schema type (json-schema-to-typescript)
//   events.ts     the event registry built from the x-events catalogue
//
// Usage: node contracts/codegen/gen_ts.mjs [--check]

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const tsDir = join(root, "typescript");
const require = createRequire(join(tsDir, "package.json"));
const { compile } = require("json-schema-to-typescript");

const HEADER = "// Generated by contracts/codegen/gen_ts.mjs from contracts/schema. Do not edit.\n";
const bundle = JSON.parse(readFileSync(join(root, "dist", "inspiration.schema.json"), "utf8"));

// Keywords next to a $ref (usually a field description) make json-schema-to-typescript
// emit a numbered copy of the referenced type (Instant1, Instant2...), so drop them. Field
// descriptions stay in the schema and the Python models.
function stripRefSiblings(node) {
  if (Array.isArray(node)) return node.map(stripRefSiblings);
  if (node && typeof node === "object") {
    if ("$ref" in node) return { $ref: node.$ref };
    return Object.fromEntries(Object.entries(node).map(([k, v]) => [k, stripRefSiblings(v)]));
  }
  return node;
}

// json-schema-to-typescript names types from `title`; give every definition its own name
// so references resolve to named types instead of inlined copies.
function withTitles(schema) {
  const copy = structuredClone(schema);
  copy.$defs = stripRefSiblings(copy.$defs);
  for (const [name, def] of Object.entries(copy.$defs)) def.title = name;
  // Root: an object that references every definition, so all are emitted and the root
  // itself can be dropped.
  delete copy.title;
  copy.type = "object";
  copy.additionalProperties = false;
  copy.properties = Object.fromEntries(Object.keys(copy.$defs).map((n) => [n, { $ref: `#/$defs/${n}` }]));
  return copy;
}

async function generateTypes() {
  let ts = await compile(withTitles(bundle), "InspirationContractsRoot", {
    bannerComment: "",
    additionalProperties: false,
    unreachableDefinitions: false,
    declareExternallyReferenced: true,
    enableConstEnums: false,
    strictIndexSignatures: true,
    format: true,
    style: { semi: true, singleQuote: false, printWidth: 100 },
  });
  // Drop the synthetic root interface.
  ts = ts.replace(/export interface InspirationContractsRoot \{[\s\S]*?\n\}\n/, "");
  return HEADER + "\n" + ts.trimStart();
}

function generateEvents() {
  const events = bundle["x-events"];
  const payloads = [...new Set(Object.values(events).map((e) => e.payload))].sort();
  const lines = [
    HEADER,
    `import type { EventEnvelope, ${payloads.join(", ")} } from "./generated.js";`,
    "",
    "/** Payload type for each event type in the catalogue. */",
    "export interface EventPayloads {",
    ...Object.entries(events).map(([t, e]) => `  "${t}": ${e.payload};`),
    "}",
    "",
    "export type EventTypeName = keyof EventPayloads;",
    "",
    "export const EVENT_VERSIONS: Readonly<Record<EventTypeName, number>> = {",
    ...Object.entries(events).map(([t, e]) => `  "${t}": ${e.version},`),
    "};",
    "",
    "/** An envelope whose data is typed by its event type. */",
    "export type TypedEvent<T extends EventTypeName = EventTypeName> = {",
    '  [K in T]: Omit<EventEnvelope, "type" | "data"> & { type: K; data: EventPayloads[K] };',
    "}[T];",
    "",
  ];
  return lines.join("\n");
}

const outputs = {
  [join(tsDir, "src", "generated.ts")]: await generateTypes(),
  [join(tsDir, "src", "events.ts")]: generateEvents(),
};

const check = process.argv.includes("--check");
const stale = Object.entries(outputs).filter(([p, text]) => !existsSync(p) || readFileSync(p, "utf8") !== text);
if (check) {
  for (const [p] of stale) console.error(`gen_ts: ${p} is stale; run \`make contracts\``);
  process.exit(stale.length ? 1 : 0);
}
for (const [p, text] of Object.entries(outputs)) writeFileSync(p, text);
console.log(`gen_ts: wrote ${Object.keys(outputs).length} files`);
