"""Bundle contracts/schema/*.yaml into one JSON Schema document.

Every type in every file lands in one flat $defs namespace, so type names must be unique
across files. Cross-file references ("knowledge.yaml#/$defs/Claim") are rewritten to local
ones ("#/$defs/Claim"). The bundle is the input for every code generator and is committed
at contracts/dist/inspiration.schema.json for consumers in other languages.

Usage: python contracts/codegen/bundle.py [--check]
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

import yaml
from jsonschema import Draft202012Validator

ROOT = Path(__file__).resolve().parents[1]
SCHEMA_DIR = ROOT / "schema"
DIST = ROOT / "dist" / "inspiration.schema.json"
BUNDLE_ID = "https://schemas.inspiration.local/contracts/v1/inspiration.schema.json"

REF = re.compile(r"^(?P<file>[a-z_]+\.yaml)?#/\$defs/(?P<name>[A-Za-z0-9]+)$")

# Unions whose members share a constant tag field. The bundler adds an OpenAPI-style
# "discriminator" keyword (ignored by JSON Schema validators) so pydantic and TypeScript
# generators produce tagged unions.
DISCRIMINATORS = {
    "Block": "type",
    "DataRef": "kind",
    "ViewHostMessage": "type",
    "ViewGuestMessage": "type",
}


class BundleError(Exception):
    pass


def load_sources() -> dict[str, dict[str, Any]]:
    sources = {}
    for path in sorted(SCHEMA_DIR.glob("*.yaml")):
        with path.open(encoding="utf-8") as f:
            doc = yaml.safe_load(f)
        if doc.get("$id") != path.name:
            raise BundleError(f"{path.name}: $id must be {path.name!r}")
        sources[path.name] = doc
    return sources


def rewrite_refs(node: Any, current_file: str, defined: dict[str, str]) -> Any:
    if isinstance(node, dict):
        out = {}
        for key, value in node.items():
            if key == "$ref":
                m = REF.match(value)
                if not m:
                    raise BundleError(f"{current_file}: unsupported $ref {value!r}")
                target_file = m.group("file") or current_file
                name = m.group("name")
                if defined.get(name) != target_file:
                    raise BundleError(f"{current_file}: $ref {value!r} does not resolve")
                out[key] = f"#/$defs/{name}"
            else:
                out[key] = rewrite_refs(value, current_file, defined)
        return out
    if isinstance(node, list):
        return [rewrite_refs(v, current_file, defined) for v in node]
    return node


def bundle() -> dict[str, Any]:
    sources = load_sources()
    defined: dict[str, str] = {}
    for file, doc in sources.items():
        for name in doc.get("$defs", {}):
            if name in defined:
                raise BundleError(f"type {name!r} defined in both {defined[name]} and {file}")
            defined[name] = file

    defs: dict[str, Any] = {}
    events: dict[str, Any] = {}
    files: dict[str, list[str]] = {}
    for file, doc in sources.items():
        files[file.removesuffix(".yaml")] = list(doc.get("$defs", {}))
        for name, schema in doc.get("$defs", {}).items():
            defs[name] = rewrite_refs(schema, file, defined)
        for event_type, spec in doc.get("x-events", {}).items():
            if spec["payload"] not in defined:
                raise BundleError(f"event {event_type}: unknown payload {spec['payload']}")
            events[event_type] = spec

    for name, tag in DISCRIMINATORS.items():
        union = defs[name]
        mapping = {}
        for member in union["oneOf"]:
            member_name = member["$ref"].rsplit("/", 1)[1]
            const = defs[member_name]["properties"][tag]["const"]
            mapping[const] = member["$ref"]
        union["discriminator"] = {"propertyName": tag, "mapping": mapping}

    result = {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": BUNDLE_ID,
        "title": "Inspiration contracts",
        "description": "Generated by contracts/codegen/bundle.py. Do not edit.",
        "x-events": events,
        "x-files": files,
        "$defs": dict(sorted(defs.items())),
    }
    Draft202012Validator.check_schema(result)
    return result


def render(doc: dict[str, Any]) -> str:
    return json.dumps(doc, ensure_ascii=False, indent=2) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if the committed bundle is stale")
    args = parser.parse_args()
    try:
        text = render(bundle())
    except BundleError as e:
        print(f"bundle: {e}", file=sys.stderr)
        return 1
    if args.check:
        if not DIST.exists() or DIST.read_text(encoding="utf-8") != text:
            print("bundle: contracts/dist/inspiration.schema.json is stale; run `make contracts`", file=sys.stderr)
            return 1
        return 0
    DIST.parent.mkdir(parents=True, exist_ok=True)
    DIST.write_text(text, encoding="utf-8")
    print(f"bundle: wrote {DIST.relative_to(ROOT.parent)} ({len(json.loads(text)['$defs'])} types)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
